"""Business, Product, and OnboardingMessage database models (PRD §12.3, §36.11)."""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from app.models.program import Program
    from app.models.user import User


class Business(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Business entity owned by an entrepreneur (PRD §12.3)."""

    __tablename__ = "businesses"
    __table_args__ = (
        Index("ix_businesses_owner_id", "owner_id", unique=True),
        Index("ix_businesses_program_id", "program_id"),
    )

    owner_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
    )
    program_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("programs.id", ondelete="SET NULL"),
        nullable=True,
    )
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    niche: Mapped[str] = mapped_column(String(50), nullable=False)
    city: Mapped[str] = mapped_column(String(100), nullable=False)
    area: Mapped[str | None] = mapped_column(String(100), nullable=True)
    budget_pkr: Mapped[int] = mapped_column(Integer, nullable=False)
    hours_per_week: Mapped[int] = mapped_column(Integer, nullable=False)
    tone: Mapped[str] = mapped_column(String(50), server_default="friendly", nullable=False)
    languages: Mapped[list[str]] = mapped_column(ARRAY(String(20)), nullable=False)
    platforms: Mapped[list[str]] = mapped_column(ARRAY(String(50)), nullable=False)
    target_customer: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Relationships
    owner: Mapped["User"] = relationship("User", foreign_keys=[owner_id], lazy="joined")
    program: Mapped["Program | None"] = relationship(
        "Program", foreign_keys=[program_id], lazy="select"
    )

    products: Mapped[list["Product"]] = relationship(
        "Product",
        back_populates="business",
        cascade="all, delete-orphan",
        lazy="select",
    )
    validation_report: Mapped["ValidationReport | None"] = relationship(
        "ValidationReport",
        back_populates="business",
        uselist=False,
        cascade="all, delete-orphan",
        lazy="select",
    )
    pricing_results: Mapped[list["PricingResult"]] = relationship(
        "PricingResult",
        back_populates="business",
        cascade="all, delete-orphan",
        lazy="select",
    )


class Product(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Product or service offering of a business (PRD §12.3, F-005)."""

    __tablename__ = "products"
    __table_args__ = (Index("ix_products_business_id", "business_id"),)

    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
    )
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    cost_inputs: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB,
        server_default="[]",
        nullable=False,
    )
    price_pkr: Mapped[int] = mapped_column(Integer, nullable=False)

    business: Mapped["Business"] = relationship("Business", back_populates="products")


class OnboardingMessage(Base, UUIDPrimaryKeyMixin):
    """Conversational onboarding message between entrepreneur and Hunar assistant (F-003)."""

    __tablename__ = "onboarding_messages"
    __table_args__ = (
        CheckConstraint(
            "role IN ('user', 'assistant', 'system')",
            name="check_onboarding_message_role",
        ),
        Index("ix_onboarding_messages_user_id_created_at", "user_id", "created_at"),
    )

    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )
    role: Mapped[str] = mapped_column(String(20), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    meta: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        server_default="{}",
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )


class ValidationReport(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Idea validation report generated by Validator agent (PRD §12.3, §36.12, F-006)."""

    __tablename__ = "validation_reports"
    __table_args__ = (
        Index("ix_validation_reports_business_id", "business_id", unique=True),
        CheckConstraint(
            "confidence IN ('low', 'medium', 'high')",
            name="check_validation_report_confidence",
        ),
    )

    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
    )
    competitors: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB,
        server_default="[]",
        nullable=False,
    )
    how_to_be_better: Mapped[list[str]] = mapped_column(
        ARRAY(Text),
        server_default="{}",
        nullable=False,
    )
    confidence: Mapped[str] = mapped_column(String(20), nullable=False, server_default="medium")
    demand_summary: Mapped[str] = mapped_column(Text, nullable=False, server_default="")
    pricing_insight: Mapped[str] = mapped_column(Text, nullable=False, server_default="")
    reasoning: Mapped[str] = mapped_column(Text, nullable=False, server_default="")

    business: Mapped["Business"] = relationship("Business", back_populates="validation_report")


class PricingResult(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Pricing calculation and break-even analysis for a product (PRD §12.3, §36.13, F-007)."""

    __tablename__ = "pricing_results"
    __table_args__ = (
        Index("ix_pricing_results_business_id", "business_id"),
        Index("ix_pricing_results_product_id", "product_id"),
    )

    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
    )
    product_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("products.id", ondelete="SET NULL"),
        nullable=True,
    )
    product_name: Mapped[str] = mapped_column(String(200), nullable=False)
    assumptions: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        server_default="{}",
        nullable=False,
    )
    unit_cost: Mapped[int] = mapped_column(Integer, nullable=False)
    price: Mapped[int] = mapped_column(Integer, nullable=False)
    margin_pct: Mapped[float] = mapped_column(nullable=False)
    break_even_units: Mapped[int] = mapped_column(Integer, nullable=False)
    risk_flags: Mapped[list[str]] = mapped_column(
        ARRAY(Text),
        server_default="{}",
        nullable=False,
    )
    notes: Mapped[str] = mapped_column(Text, server_default="", nullable=False)
    approved_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    business: Mapped["Business"] = relationship("Business", back_populates="pricing_results")
    product: Mapped["Product | None"] = relationship("Product", lazy="select")
