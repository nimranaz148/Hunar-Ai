"""Planning domain database models: LaunchPlan, PlanTask, and Proposal (PRD §12.1, §36.7, §36.14, F-008, F-009)."""

import uuid
from datetime import date, datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from app.models.business import Business


class LaunchPlan(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """30-day launch roadmap generated by Launch Planner agent (PRD §12.1, §36.14, F-008, F-009)."""

    __tablename__ = "launch_plans"
    __table_args__ = (
        CheckConstraint(
            "status IN ('not_started', 'in_progress', 'awaiting_approval', 'approved', 'revision_requested')",
            name="check_launch_plan_status",
        ),
        Index("ix_launch_plans_business_id", "business_id", unique=True),
    )

    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
    )
    status: Mapped[str] = mapped_column(
        String(30), server_default="awaiting_approval", nullable=False
    )
    summary: Mapped[str] = mapped_column(Text, server_default="", nullable=False)
    revision_notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    approved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    business: Mapped["Business"] = relationship("Business", lazy="select")
    tasks: Mapped[list["PlanTask"]] = relationship(
        "PlanTask",
        back_populates="plan",
        cascade="all, delete-orphan",
        order_by="PlanTask.week, PlanTask.order_index",
        lazy="select",
    )


class PlanTask(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Dated, actionable task within a 30-day launch plan (PRD §12.1, §36.14, F-009)."""

    __tablename__ = "plan_tasks"
    __table_args__ = (
        CheckConstraint(
            "status IN ('pending', 'in_progress', 'completed', 'skipped')",
            name="check_plan_task_status",
        ),
        CheckConstraint("week BETWEEN 1 AND 4", name="check_plan_task_week_range"),
        Index("ix_plan_tasks_plan_id", "plan_id"),
        Index("ix_plan_tasks_due_date", "due_date"),
    )

    plan_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("launch_plans.id", ondelete="CASCADE"),
        nullable=False,
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[str] = mapped_column(Text, server_default="", nullable=False)
    week: Mapped[int] = mapped_column(Integer, nullable=False)
    category: Mapped[str] = mapped_column(String(50), server_default="setup", nullable=False)
    due_date: Mapped[date | None] = mapped_column(Date, nullable=True)
    status: Mapped[str] = mapped_column(String(30), server_default="pending", nullable=False)
    order_index: Mapped[int] = mapped_column(Integer, server_default="0", nullable=False)

    plan: Mapped["LaunchPlan"] = relationship("LaunchPlan", back_populates="tasks")


class Proposal(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Agent proposal awaiting a human gate decision (PRD §12.1, §36.7, F-008, F-010, F-017)."""

    __tablename__ = "proposals"
    __table_args__ = (
        CheckConstraint(
            "status IN ('pending', 'approved', 'rejected')",
            name="check_proposal_status",
        ),
        CheckConstraint(
            "gate_type IN ('plan_approval', 'content_outline', 'weekly_review')",
            name="check_proposal_gate_type",
        ),
        Index("ix_proposals_business_id", "business_id"),
        Index("ix_proposals_gate_type_status", "gate_type", "status"),
    )

    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
    )
    run_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("agent_runs.id", ondelete="SET NULL"),
        nullable=True,
    )
    gate_type: Mapped[str] = mapped_column(String(50), nullable=False)
    payload: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        server_default="{}",
        nullable=False,
    )
    status: Mapped[str] = mapped_column(String(30), server_default="pending", nullable=False)
    rejection_reason: Mapped[str | None] = mapped_column(Text, nullable=True)
    decided_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    business: Mapped["Business"] = relationship("Business", lazy="select")
